"""Assignment 0 (evaluation part): loss / gradient-norm correlation metrics.

Runs the ``EvalRunner`` on the Gaussian test set regenerated by
``scripts/infer_gaussian.py`` ("the test dataset from the previous part"),
computing per-example test loss and per-example gradient norm, their overall
correlation, and histograms of these metrics over batches.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from torch.utils.data import DataLoader, TensorDataset

from data8014.config import FIGURE_DIR, GAUSSIAN_CKPT_PATH, GAUSSIAN_TEST_SET_PATH, ensure_directories, get_device
from data8014.evaluation.runner import EvalRunner, plot_eval_result
from data8014.utils.io import load_tensors


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--test-file", type=Path, default=GAUSSIAN_TEST_SET_PATH,
                        help="test set saved by scripts/infer_gaussian.py")
    parser.add_argument("--checkpoint", type=Path, default=GAUSSIAN_CKPT_PATH)
    parser.add_argument("--batch-size", type=int, default=500,
                        help="evaluation batch size; 10,000/500 = 20 batches")
    parser.add_argument("--out-dir", type=Path, default=FIGURE_DIR)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if not args.test_file.exists():
        sys.exit(f"test set not found at {args.test_file}; run scripts/infer_gaussian.py first")
    if not args.checkpoint.exists():
        sys.exit(f"checkpoint not found at {args.checkpoint}; run scripts/train_gaussian.py first")

    ensure_directories()
    device = get_device()
    print(f"device: {device}")

    tensors = load_tensors(args.test_file)
    test_set = TensorDataset(tensors["X"], tensors["y"])
    loader = DataLoader(test_set, batch_size=args.batch_size)

    runner = EvalRunner.from_checkpoint(args.checkpoint, device)
    result = runner.run(loader)

    print("--- evaluation summary ---")
    print(result.summary_str())

    figures = plot_eval_result(result, args.out_dir)
    print("figures:")
    for figure in figures:
        print(f"  {figure}")


if __name__ == "__main__":
    main()
